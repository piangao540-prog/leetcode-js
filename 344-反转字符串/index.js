// 344. 反转字符串
// 考点:双指针
// 难度:Easy

// 思路:l 从最左边、r 从最右边往中间夹;每轮交换 s[l] 和 s[r],换完 l++、r--;当 l >= r 就停
// 复杂度:时间 O(n) / 空间 O(1)(只有 l、r、temp 三个数字,没开新数组)

// 注意:奇数长度停在 l == r(中间那个字符跟自己对上,本来就不用动),偶数长度停在 l > r(两指针交错而过)
// 注意:写成 l <= r 不会报错也不会越界,只是多跑一轮"自己跟自己换",白做;考点就在这个边界上
// 注意:必须原地——原地改传进来的 s,不返回新数组;三行交换可写成 [s[l], s[r]] = [s[r], s[l]],但解构会造个临时数组,严格说也是 O(1)

var reverseString = function (s) {
    let l = 0
    let r = s.length - 1
    while (l < r) {
        const temp = s[r]
        s[r] = s[l]
        s[l] = temp
        l++
        r--
    }
    return s
}
